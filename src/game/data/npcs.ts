/** 대화 한 번에 API 로 보내는 게임 상황 */
export interface NpcContext {
  day: number;
  clock: string;
  partOfDay: string;
  onShift: boolean;
  shift?: { left: string; checked: number; patrols: number; robbers: number; pay: number; alert: string | null };
  player: { level: number; gold: number; hunger: number; fatigue: number; hp: number; maxHp: number };
  pastShifts: number;
  affinity: number;
  canGift: boolean;
  memories: string[];
  /** NPC 가 지금 어디서 뭘 하는지 (예: 반장실에 앉아 일 보는 중 / 3층 순찰 중) */
  doing?: string;
  /** 엄마가 보기에 딸인지 아들인지 */
  child?: '딸' | '아들';
  /** 오늘 냉장고에 든 음식 수 */
  fridge?: number;
}

export interface NpcReply {
  reply: string;
  emotion: NpcEmotion;
  /** 플레이어 쪽 기분 (없으면 기본) */
  playerMood?: PlayerMood;
  affinity: number;
  memory: string;
  gift: boolean;
  /** API 키가 없어 미리 써 둔 대사로 답했다 */
  offline?: boolean;
}
