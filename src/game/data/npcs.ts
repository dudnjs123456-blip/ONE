/**
 * 대화형 NPC (LLM 으로 자유롭게 대화한다).
 * 성격·말투는 persona 에 고정해 두고, 그때그때의 상황(시각·근무 현황·기억)은 대화할 때마다 따로 넘긴다.
 */

export interface NpcDef {
  id: string;
  name: string;
  /** 머리 위 이름표·대화창 제목 */
  title: string;
  face: string;
  /** 처음 만났을 때 호감도 (0~100) */
  startAffinity: number;
  /** AI 에게 주는 고정 설정 (서버에서만 쓴다) */
  persona: string;
  /** 대화창 아래 추천 질문 */
  suggestions: string[];
  /** 대화창에서 부르는 짧은 이름 (예: 박 반장, 엄마) */
  callName: string;
  /** 꽃을 건넬 때 하는 말 */
  flowerLine: string;
  /** 하루 한 번 주는 선물 (커피·집밥) */
  gift: { label: string; fatigue: number; hunger: number };
  /** AI 가 답을 못 할 때의 대사: 거절 · 빈 답 · 너무 자주 · 오류 */
  soft: { refusal: string; empty: string; busy: string; error: string };
}

